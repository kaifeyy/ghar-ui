// Extracts every t('...') / msg('...') / plural(..., '...', '...') literal into src/i18n/en.ts,
// and reports which keys each translation catalogue is missing.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join } from 'node:path';
const root = new URL('../src/', import.meta.url).pathname;
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) { if (!p.includes('/i18n')) walk(p); } else if (/\.(tsx?|ts)$/.test(f) && !/\.test\./.test(f)) files.push(p); } })(root);
const keys = new Set();
const re = /\b(?:t|msg|toast)\(\s*'((?:[^'\\]|\\.)*)'/g;
const tern = /\b(?:t|toast)\(\s*[^'"\n()]*?\?\s*'((?:[^'\\]|\\.)*)'\s*:\s*'((?:[^'\\]|\\.)*)'/g;
const pl = /\bplural\(\s*t\s*,[^,]+,\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'/g;
for (const f of files) {
  const s = readFileSync(f, 'utf8');
  for (const m of s.matchAll(re)) keys.add(m[1]);
  for (const m of s.matchAll(pl)) { keys.add(m[1]); keys.add(m[2]); }
  for (const m of s.matchAll(tern)) { keys.add(m[1]); keys.add(m[2]); }
}
const sorted = [...keys].sort((a, b) => a.localeCompare(b));
const esc = k => k.replace(/\\'/g, "'").replace(/\\/g, '\\\\').replace(/'/g, "\\'");
writeFileSync(join(root, 'i18n/en.ts'), `// Generated by scripts/i18n-extract.mjs — source strings (English).\nconst en = {\n${sorted.map(k => `  '${esc(k)}': '${esc(k)}',`).join('\n')}\n} as const;\nexport default en;\n`);
for (const lang of ['ur', 'ar', 'hi']) {
  const p = join(root, `i18n/${lang}.ts`);
  if (!existsSync(p)) continue;
  const src = readFileSync(p, 'utf8');
  const have = new Set([...src.matchAll(/^\s*'((?:[^'\\]|\\.)*)':/gm)].map(m => m[1].replace(/\\'/g, "'").replace(/\\\\/g, '\\')));
  const missing = sorted.filter(k => !have.has(k.replace(/\\'/g, "'")));
  console.log(`${lang}: ${have.size} entries, ${missing.length} missing`);
  if (process.argv.includes('--missing')) writeFileSync(join(root, `../scripts/missing-${lang}.json`), JSON.stringify(missing.map(k => k.replace(/\\'/g, "'")), null, 1));
}
console.log(`en: ${sorted.length} keys`);
