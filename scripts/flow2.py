"""Drives the new flows: custom select/date picker, checkout, context menus, social linking, admin, chat search."""
import asyncio, sys, os
from playwright.async_api import async_playwright
sys.path.insert(0, os.path.dirname(__file__))
from shot import page
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT=ROOT+'/shots/flows'
async def main():
    w=int(sys.argv[1]) if len(sys.argv)>1 else 1440
    errs=[]; os.makedirs(OUT,exist_ok=True)
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx,pg=await page(b,w,{390:844,768:1024}.get(w,900),errs)
        S=lambda n: pg.screenshot(path=f'{OUT}/{w}-{n}.png')
        st=lambda js: pg.evaluate(js)
        # 1. checkout success
        await st("__ghar.openModal({kind:'gift',to:'ayesha'})"); await pg.wait_for_timeout(300); await S('checkout-review')
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(700); await S('checkout-processing')
        await pg.wait_for_timeout(1700); await S('checkout-success')
        print('checkout success:', await pg.locator('dialog[open] .pay-result').inner_text())
        await pg.click('dialog[open] .dlg-foot button'); await pg.wait_for_timeout(200)
        # 2. failure then retry (outcome forced via dev state, not the UI)
        await st("__ghar.useApp.setState(s=>{s.nextOutcome='failure'})")
        await st("__ghar.openModal({kind:'buyPoints'})"); await pg.wait_for_timeout(200)
        print('outcome picker in dialog:', await pg.locator('dialog[open] select, dialog[open] .test-outcome').count())
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(2100); await S('checkout-failed')
        print('failed:', (await pg.locator('dialog[open] .pay-result').inner_text()).replace('\n',' | '))
        await pg.click('dialog[open] button:has-text("Try again")'); await pg.wait_for_timeout(2100)
        print('retry ->', (await pg.locator('dialog[open] .pay-result b').inner_text()))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        # 3. cancel during processing
        await st("__ghar.openModal({kind:'addMoney'})"); await pg.wait_for_timeout(200)
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(400)
        await pg.click('dialog[open] button:has-text("Cancel payment")'); await pg.wait_for_timeout(300)
        print('cancel ->', await pg.locator('dialog[open] .pay-result b').inner_text())
        bal=await st("__ghar.useApp.getState().transactions.length"); print('tx count', bal)
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        # 4. custom select keyboard inside dialog
        await st("__ghar.openModal({kind:'createChannel',serverId:'cf'})"); await pg.wait_for_timeout(300)
        trig=pg.locator('dialog[open] .sel-trigger').first
        await trig.focus(); await pg.keyboard.press('ArrowDown'); await pg.wait_for_timeout(200); await S('select-open')
        vis=await pg.evaluate("()=>{const p=document.querySelector('.sel-pop:popover-open, .sel-pop:not([hidden])');if(!p)return null;const r=p.getBoundingClientRect();return [Math.round(r.top),Math.round(r.bottom),innerHeight]}")
        print('select popover rect', vis)
        await pg.keyboard.press('ArrowDown'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(150)
        print('select value now:', await trig.inner_text(), '| focus back on trigger:', await pg.evaluate("document.activeElement.classList.contains('sel-trigger')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        # 5. date picker (DOB in settings) keyboard
        await st("location.hash='#/settings/account'"); await pg.wait_for_timeout(400)
        dp=pg.locator('.field:has(.flabel:has-text("Date of birth")) .sel-trigger')
        before=await dp.inner_text(); await dp.click(); await pg.wait_for_timeout(200); await S('datepicker')
        await pg.keyboard.press('ArrowRight'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(200)
        print('dob', before.strip(), '->', (await dp.inner_text()).strip(), await st("__ghar.useApp.getState().dob"))
        # 6. context menu on a DM row and a message
        await st("location.hash='#/inbox'"); await pg.wait_for_timeout(300)
        if w>859:
            await pg.locator('[data-ctx=conversation]').first.click(button='right'); await pg.wait_for_timeout(200); await S('ctx-conversation')
            print('conv menu:', (await pg.locator('[role=menu]').inner_text()).replace('\n',' / '))
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
        await st("location.hash='#/c/kd/kd-general'"); await pg.wait_for_timeout(400)
        await pg.locator('li.msg .mtext').first.click(button='right'); await pg.wait_for_timeout(200); await S('ctx-message')
        print('msg menu:', (await pg.locator('[role=menu]').inner_text()).replace('\n',' / '))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
        await pg.locator('li.msg .av').first.click(button='right'); await pg.wait_for_timeout(200)
        m=pg.locator('[role=menu]'); r=await m.bounding_box(); print('user menu inside viewport:', r['x']>=0 and r['y']>=0 and r['x']+r['width']<=w)
        await pg.click('[role=menu] >> text=View profile'); await pg.wait_for_timeout(300); print('after view profile route:', await st("location.hash"))
        # native menu preserved in composer
        await st("location.hash='#/c/kd/kd-general'"); await pg.wait_for_timeout(300)
        prevented=await pg.evaluate("()=>{const ta=document.querySelector('.composer textarea, textarea');const e=new MouseEvent('contextmenu',{bubbles:true,cancelable:true});ta.dispatchEvent(e);return e.defaultPrevented}")
        print('composer contextmenu prevented:', prevented)
        # 7. social link connect
        await st("location.hash='#/settings/connections'"); await pg.wait_for_timeout(300); await S('connections')
        await pg.click('.social-row:has-text("TikTok") button:has-text("Connect")'); await pg.wait_for_timeout(200)
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(150); print('empty error:', await pg.locator('dialog[open] .ferr').inner_text())
        await pg.fill('dialog[open] input', 'https://www.tiktok.com/@kaif.clips'); await pg.wait_for_timeout(100); await S('connect-dialog')
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(1300)
        print('tiktok row:', (await pg.locator('.social-row:has-text("TikTok")').inner_text()).replace('\n',' / '))
        # 8. admin
        await st("__ghar.useApp.setState(s=>{s.staffAuthed=false})"); await st("location.hash='#/staff/users'"); await pg.wait_for_timeout(300)
        print('gate shown:', await pg.locator('.gate-card').count())
        await st("__ghar.useApp.setState(s=>{s.staffAuthed=true})"); await pg.wait_for_timeout(300)
        await pg.click('.ticket-row:has-text("Hamza")'); await pg.click('button:has-text("Suspend")'); await pg.wait_for_timeout(150)
        print('reason error:', await pg.locator('.ferr').first.inner_text())
        await pg.fill('textarea >> nth=0', 'Spamming invite links in #general'); await pg.click('button:has-text("Suspend")'); await pg.wait_for_timeout(200); await S('admin-users')
        print('suspended:', await st("Object.keys(__ghar.useApp.getState().suspensions)"))
        await st("location.hash='#/staff/integrations'"); await pg.wait_for_timeout(300)
        await pg.locator('.svc-row button').first.click(); await pg.wait_for_timeout(900); await S('admin-integrations')
        print('svc check:', await st("JSON.stringify(__ghar.useApp.getState().serviceChecks)"))
        # 9. chat search combined filters
        await st("location.hash='#/search'"); await pg.wait_for_timeout(300); await S('search-empty')
        await pg.fill('#cs-q', 'physics'); await pg.wait_for_timeout(200)
        n1=await pg.locator('.cs-hit').count()
        if w<=859: await pg.click('button:has-text("Filters")'); await pg.wait_for_timeout(150)
        await pg.click('.radios-segmented .radio:has-text("Servers")'); await pg.wait_for_timeout(200)
        n2=await pg.locator('.cs-hit').count(); await S('search-filters')
        print('physics results all:', n1, 'servers only:', n2, '| status:', await pg.locator('.chat-search [role=status]').inner_text())
        await pg.fill('#cs-q', 'zzzz-no-match'); await pg.wait_for_timeout(200); await S('search-noresults')
        print('empty state:', await pg.locator('.empty').count())
        await pg.click('button:has-text("Reset all")'); await pg.fill('#cs-q', 'physics'); await pg.wait_for_timeout(200)
        await pg.locator('.cs-hit').first.click(); await pg.wait_for_timeout(600)
        print('opened:', await st("location.hash"), '| jump highlight:', await pg.locator('li.msg.is-jump').count())
        await S('search-jump')
        print('ERRORS', errs[:5])
        await b.close()
asyncio.run(main())
