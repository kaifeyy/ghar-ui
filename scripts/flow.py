"""Drive the sign-up flow end to end and capture screenshots."""
import asyncio, sys, os
from playwright.async_api import async_playwright
sys.path.insert(0, os.path.dirname(__file__))
import shot
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
async def main():
    errs=[]
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={'width':1440,'height':900})
        pg=await ctx.new_page()
        async def fr(route):
            if 'fonts.googleapis' in route.request.url: await route.fulfill(body=shot.FONTS, content_type='text/css')
            else: await route.abort()
        await pg.route("**/*fonts.g*/**", fr)
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file://'+ROOT+'/dist-single/index.html'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=ROOT+'/shots/auth-login.png')
        await pg.fill('input[autocomplete=username]','kaif'); await pg.fill('input[type=password]','wrong'); await pg.click('button[type=submit]'); await pg.wait_for_timeout(700)
        print('wrong pw note:', await pg.locator('.note-danger').inner_text())
        await pg.click('text=Create an account'); await pg.wait_for_timeout(200)
        await pg.fill('input[type=email]','a@b.co'); await pg.fill('input[type=password]','longpassword1!'); await pg.fill('input[type=date]','2015-01-01')
        await pg.click('text=I agree'); await pg.click('button[type=submit]'); await pg.wait_for_timeout(200)
        print('under13:', await pg.locator('h1').inner_text())
        await pg.click('text=Back to sign in'); await pg.click('text=Create an account')
        await pg.fill('input[type=email]','a@b.co'); await pg.fill('input[type=password]','longpassword1!'); await pg.fill('input[type=date]','2009-01-01')
        await pg.click('text=I agree'); await pg.screenshot(path=ROOT+'/shots/auth-signup.png'); await pg.click('button[type=submit]'); await pg.wait_for_timeout(200)
        print('step:', await pg.locator('h1').inner_text())
        await pg.click('text=I’ve confirmed'); await pg.wait_for_timeout(200)
        await pg.fill('input[autocomplete=off]','bilal'); await pg.wait_for_timeout(500); print('bilal:', await pg.locator('.min-row').inner_text())
        await pg.fill('input[autocomplete=off]','newperson_1'); await pg.wait_for_timeout(500); print('new:', await pg.locator('.min-row').inner_text())
        await pg.screenshot(path=ROOT+'/shots/auth-username.png')
        await pg.click('button[type=submit]'); await pg.wait_for_timeout(200)
        print('step:', await pg.locator('h1').inner_text())
        await pg.click('text=Skip for now'); await pg.wait_for_timeout(300)
        await pg.click('button:has-text("Study")'); await pg.screenshot(path=ROOT+'/shots/onboarding-1.png'); await pg.click('text=Continue'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=ROOT+'/shots/onboarding-2.png')
        await pg.locator('.ob-row button').first.click(); await pg.wait_for_timeout(200)
        await pg.click('text=Go to Ghar'); await pg.wait_for_timeout(400)
        st=await pg.evaluate("()=>{const s=__ghar.useApp.getState();return [s.ageGroup,s.users.me.handle,s.authed,s.authStep, s.prefs.privacy.dmsFromNonFriends]}")
        print('state:', st)
        await pg.keyboard.press('Control+Shift+D'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=ROOT+'/shots/devtools.png')
        await pg.click('role=tab[name="Requirements"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=ROOT+'/shots/devtools-trace.png')
        print('ERRORS', errs)
        await b.close()
asyncio.run(main())
